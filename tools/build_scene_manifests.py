"""Build renderer-neutral scene manifests for the Digital World scene layer.

One config per File Island region; the output is authored as the Godot scene
description (objects placed in a 960x720 design space, matching the panel's
scene canvas) and consumed by the DSH plugin's web renderer. Fields:

  kind       ground style the renderer fills (city/forest/gym/desert/coast/
             snow/swamp/machine/volcano)
  palette    sky/ground gradients, far hill color, accent
  objects    placed props; `facility` maps to the seven File City facilities
  actors     ambient Digimon allowed in the region (real Wikimon species)

Run:
  python tools/build_scene_manifests.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GODOT_OUT = ROOT / "godot-digital-world" / "assets" / "scenes"
PLUGIN_OUT = ROOT / "plugins" / "dsh-plugin-digital-world" / "lib" / "scene-data.js"
CLIENT_JS = ROOT / "plugins" / "dsh-plugin-digital-world" / "lib" / "client.js"
CLIENT_V2 = ROOT / "plugins" / "dsh-plugin-digital-world" / "lib" / "client-0.19.0.js"
CLIENT_BEGIN = "// >>> SCENE-DATA"
CLIENT_END = "// <<< SCENE-DATA <<<"


def patch_client(typed: list[dict]) -> None:
    """Inline the manifests into the prebuilt browser bundle between markers."""
    text = CLIENT_JS.read_text(encoding="utf-8")
    payload = json.dumps({m["id"]: m for m in typed}, ensure_ascii=False, separators=(",", ":"))
    block = (
        "    // >>> SCENE-DATA (generated by tools/build_scene_manifests.py) >>>\n"
        f"    const REGION_SCENES = Object.freeze({payload})\n"
        "    // <<< SCENE-DATA <<<"
    )
    start = text.index(CLIENT_BEGIN)
    line_start = text.rfind("\n", 0, start) + 1
    end_marker = text.index(CLIENT_END, start)
    line_end = text.find("\n", end_marker)
    if line_end == -1:
        line_end = len(text)
    CLIENT_JS.write_text(text[:line_start] + block + text[line_end:], encoding="utf-8")


def publish_client() -> None:
    """Publish the browser bundle under a fresh filename so the Host/browser
    cannot keep serving a stale cached copy of the previous module URL."""
    CLIENT_V2.write_text(CLIENT_JS.read_text(encoding="utf-8"), encoding="utf-8")

