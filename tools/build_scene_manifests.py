def build_manifest(region: dict) -> dict:
    return {
        "schema": 1,
        "id": region["id"],
        "name": region["name"],
        "zh": region["zh"],
        "kind": region["kind"],
        "base_resolution": [320, 180],
        "display_resolution": [960, 720],
        "palette": PALETTES[region["kind"]],
        "objects": region["objects"],
        "actors": region["actors"],
        "note": "Authored in the Godot scene layer; renderer-neutral manifest consumed by the DSH plugin.",
    }


def main() -> None:
    GODOT_OUT.mkdir(parents=True, exist_ok=True)
    typed = [build_manifest(region) for region in REGIONS]

    index = []
    for manifest in typed:
        path = GODOT_OUT / f"{manifest['id']}.json"
        path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        index.append({"id": manifest["id"], "name": manifest["name"], "zh": manifest["zh"], "kind": manifest["kind"], "file": f"{manifest['id']}.json"})
    (GODOT_OUT / "index.json").write_text(
        json.dumps({"schema": 1, "scenes": index}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )

    entries = ",\n".join(
        f"  {json.dumps(m['id'])}: {json.dumps(m, ensure_ascii=False)}" for m in typed
    )
    js = (
        "/**\n"
        " * Region scene manifests for the panel renderer.\n"
        " *\n"
        " * GENERATED by tools/build_scene_manifests.py from the Godot scene layer —\n"
        " * edit the generator (or the Godot asset) and re-run it; do not hand-edit.\n"
        " */\n"
        "export const REGION_SCENES = Object.freeze({\n" + entries + ",\n})\n\n"
        "export const SCENE_IDS = Object.freeze([" + ", ".join(json.dumps(m["id"]) for m in typed) + "])\n"
    )
    PLUGIN_OUT.write_text(js, encoding="utf-8")
    patch_client(typed)
    publish_client()
    print(f"wrote {len(typed)} manifests -> {GODOT_OUT}")
    print(f"wrote scene-data.js -> {PLUGIN_OUT}")
    print(f"patched client bundle -> {CLIENT_JS} -> {CLIENT_V2.name}")


if __name__ == "__main__":
    main()
